const dateLabel = (date: string) => new Intl.DateTimeFormat('ru-RU', {
  day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC',
}).format(new Date(date + 'T12:00:00Z'))
const changesList = (changes: string[]) => `<ul>${changes.map(change => `<li>${esc(change)}</li>`).join('')}</ul>`

export function updateHistoryView() {
  return `<div class="dialog-panel">
    <div class="dialog-head"><h2>История обновлений</h2><button class="dialog-close" id="updates-back" aria-label="Назад к настройкам">‹</button></div>
    <div class="dialog-content update-history">
      <p class="updates-lead">Что нового в «Моих сменах»</p>
      ${updateHistory.map(update => `<details class="update-entry"${update.version === __APP_VERSION__ ? ' open' : ''}>
        <summary><span><b>${esc(update.version)}${update.version === __APP_VERSION__ ? ' <em>Текущая</em>' : ''}</b><span>${esc(update.title)}</span><small>${update.earlier ? 'Август — сентябрь 2026' : `<time datetime="${update.date}">${dateLabel(update.date)}</time>`}</small></span><i aria-hidden="true">⌄</i></summary>
        <div class="update-changes">${changesList(update.changes)}${(update.earlier || []).map(earlier => `<h3><time datetime="${earlier.date}">${dateLabel(earlier.date)}</time></h3>${changesList(earlier.changes)}`).join('')}</div>
      </details>`).join('')}
    </div>
    <div class="dialog-actions"><button class="primary" id="updates-close">Закрыть</button></div>
  </div>`
}
