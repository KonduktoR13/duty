import { test, expect, type Page } from '@playwright/test'
import { rosterPdf } from './fixture'

async function upload(page: Page, code: string, colleagues = ['8']) {
  await page.locator('#file').setInputFiles(rosterPdf(code, 'September', colleagues))
  const choice = page.locator('[data-delta="D12"]')
  await expect(choice.or(page.locator('#confirm-import'))).toBeVisible()
  if (await choice.isVisible()) await choice.click()
}
async function saveImport(page: Page) {
  await page.locator('#confirm-import').click()
  await expect(page.locator('#dialog')).not.toBeVisible()
}
async function cancelWork(page: Page) {
  await page.locator('.cancellation-row').filter({ hasText: '8P' }).locator('[data-cancel-shift]').click()
  await page.locator('#confirm-cancellation').click()
  await expect(page.locator('#dialog')).not.toBeVisible()
}

test('cancel a PDF shift independently from home duty, persist offline and restore with recalculated workload', async ({ page, context }) => {
  await page.setViewportSize({ width: 320, height: 780 })
  await page.goto('/')
  await upload(page, '8P')
  await saveImport(page)
  const day = page.locator('[data-day="2026-09-07"]')
  await day.click()
  await page.locator('#add-day-personal').click()
  await page.locator('[data-event-kind="home"]').click()
  await page.locator('[name="startTime"]').fill('16:00')
  await page.locator('[name="endTime"]').fill('20:00')
  await page.locator('#save-event').click()
  await expect(page.locator('#dialog')).not.toBeVisible()
  await expect(day).toHaveClass(/mixed-day-home/)
  await cancelWork(page)
  await expect(day).toHaveClass(/home-duty/)
  await expect(day.locator('.cancelled-marker')).toHaveText('⊘')
  await expect(page.locator('[data-restore-shift]')).toHaveText('Восстановить смену')
  await expect(page.locator('.personal-day-content')).toContainText('Koduvalve')
  await page.locator('#detail-close').click()
  await expect(page.locator('#shift-details')).not.toBeVisible()
  const legend = page.locator('#calendar-legend')
  await page.locator('#legend-toggle').click()
  await expect(legend).toContainText('⊘ · смена отменена вами')
  await expect(legend.locator('.legend-swatch.mixed-day-home')).toHaveCount(0)
  await page.locator('[data-section="analysis"]').click()
  await expect(page.locator('.personal-summary .pay-row').filter({ hasText: 'Отменено вами · работа' })).toContainText('8 ч')
  await page.locator('#employee-workload-toggle').click()
  await expect(page.locator('.employee-workload-own .workload-hours').first()).toHaveText('16')
  await page.locator('[data-section="calendar"]').click()
  await page.evaluate(async () => { await navigator.serviceWorker.ready })
  await context.setOffline(true)
  await page.reload()
  await expect(day).toHaveClass(/home-duty/)
  await day.click()
  await page.locator('[data-restore-shift]').click()
  await page.locator('#confirm-restore').click()
  await expect(page.locator('#dialog')).not.toBeVisible()
  await expect(day).toHaveClass(/mixed-day-home/)
  await expect(day.locator('.cancelled-marker')).toHaveCount(0)
  await page.locator('#detail-close').click()
  await expect(page.locator('#shift-details')).not.toBeVisible()
  await page.locator('#legend-toggle').click()
  await expect(legend.locator('.legend-swatch.mixed-day-home')).toHaveCount(1)
  await expect(legend.locator('.legend-swatch.mixed-duty-home')).toHaveCount(0)
  await expect(legend).not.toContainText('⊘ · смена отменена вами')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('PDF replacement keeps identical cancellations, retires missing ones and warns before reappearance', async ({ page }) => {
  await page.goto('/')
  await upload(page, '8P')
  await saveImport(page)
  const day = page.locator('[data-day="2026-09-07"]')
  await day.click()
  await cancelWork(page)
  await expect(day).toHaveClass(/day-empty/)
  await upload(page, '8P', ['12'])
  await expect(page.locator('#dialog')).toContainText('Отменена вами')
  await saveImport(page)
  await expect(day).toHaveClass(/day-empty/)
  await upload(page, '', ['12'])
  await expect(page.locator('#dialog')).toContainText('отмена завершена')
  await saveImport(page)
  await day.click()
  await expect(page.locator('.cancellation-controls')).toContainText('Смены больше нет')
  await expect(page.locator('[data-restore-shift]')).toHaveText('Скрыть отметку')
  await upload(page, '8P', ['12'])
  await expect(page.locator('#dialog')).toContainText('Смена появилась снова')
  await saveImport(page)
  await expect(day).toHaveClass(/day-schedule/)
  await day.click()
  await expect(page.locator('.cancellation-controls')).toContainText('прежняя отмена не применяется')
  await expect(page.locator('[data-cancel-shift]')).toHaveCount(1)
  // A new decision can cancel the reappeared shift again.
  await cancelWork(page)
  await expect(day).toHaveClass(/day-empty/)
})

test('manual home cancellation removes its colors and hours, restores, and survives backup roundtrip', async ({ page }) => {
  await page.goto('/')
  await page.locator('#add-personal').click()
  await page.locator('[data-event-kind="home"]').click()
  await page.locator('[name="owner"]').fill('D12')
  await page.locator('[name="start"]').fill('2026-11-19')
  await page.locator('[name="end"]').fill('2026-11-19')
  await page.locator('#save-event').click()
  await expect(page.locator('#dialog')).not.toBeVisible()
  const day = page.locator('[data-day="2026-11-19"]')
  await expect(day).toHaveClass(/home-duty/)
  await page.locator('[data-cancel-shift]').click()
  await page.locator('#confirm-cancellation').click()
  await expect(page.locator('#dialog')).not.toBeVisible()
  await expect(day).toHaveClass(/day-empty/)
  await expect(page.locator('.sync-card small')).toContainText('0 подтверждённых событий')
  await page.locator('[data-section="documents"]').click()
  const downloadPromise = page.waitForEvent('download')
  await page.locator('#export-backup').click()
  const file = await downloadPromise
  const path = (await file.path())!
  const chooser = page.waitForEvent('filechooser')
  await page.locator('#import-backup').click()
  await (await chooser).setFiles(path)
  await expect(page.locator('#restore-backup')).toBeVisible()
  await page.locator('#restore-backup').click()
  await expect(page.locator('#dialog')).not.toBeVisible()
  await page.locator('[data-section="calendar"]').click()
  await page.locator('#list-mode').click()
  await page.locator('[data-cancel-day]').click()
  await page.locator('[data-restore-shift]').click()
  await page.locator('#confirm-restore').click()
  await expect(page.locator('#dialog')).not.toBeVisible()
  await page.locator('#grid-mode').click()
  await expect(day).toHaveClass(/home-duty/)
  await expect(page.locator('.sync-card small')).toContainText('1 подтверждённых событий')
})

test('restoration requires resolving a replacement manual shift rather than double counting', async ({ page }) => {
  await page.goto('/')
  await upload(page, '8P')
  await saveImport(page)
  const day = page.locator('[data-day="2026-09-07"]')
  await day.click()
  await cancelWork(page)
  await page.locator('#add-day-personal').click()
  await page.locator('[data-event-kind="extra"]').click()
  await page.locator('[data-duration="8"]').click()
  await page.locator('#save-event').click()
  await expect(page.locator('#dialog')).not.toBeVisible()
  await expect(day).toHaveClass(/day-schedule/)
  await page.locator('[data-restore-shift]').click()
  await expect(page.locator('#dialog')).toContainText('Есть пересечение')
  await expect(page.locator('#confirm-restore')).toHaveCount(0)
  await page.locator('#cancel').click()
  await expect(day.locator('.cancelled-marker')).toHaveText('⊘')
})
